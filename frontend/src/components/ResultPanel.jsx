// ── Play audio using Web Speech API ───────────────────────────────────────
function playAudio(r) {
  if (!('speechSynthesis' in window)) {
    alert('Speech synthesis is not supported in your browser.')
    return
  }

  // Stop any ongoing speech
  speechSynthesis.cancel()

  // Build text to be spoken
  let speechText = `LexBrief Legal Analysis. Document Type: ${r.document_type || 'Unknown'}. Risk Level: ${r.risk_level || 'Unknown'}. `
  
  if (r.executive_summary) {
    speechText += `Executive Summary: ${r.executive_summary}. `
  }

  if (r.parties?.length) {
    speechText += `Parties involved: `
    r.parties.forEach(p => {
      speechText += `${p.role}: ${p.name}. `
    })
  }

  if (r.key_points?.length) {
    speechText += `Key points: `
    r.key_points.forEach((p, i) => {
      speechText += `${i + 1}. ${p}. `
    })
  }

  if (r.obligations?.length) {
    speechText += `Obligations and duties: `
    r.obligations.forEach((o, i) => {
      speechText += `${i + 1}. ${o}. `
    })
  }

  if (r.risks?.length) {
    speechText += `Risk flags: `
    r.risks.forEach((risk, i) => {
      speechText += `${i + 1}. ${risk}. `
    })
  }

  if (r.important_dates?.length) {
    speechText += `Important dates: `
    r.important_dates.forEach(d => {
      speechText += `${d.label}: ${d.value}. `
    })
  }

  speechText += 'Generated by LexBrief AI Legal Summarizer.'

  const utterance = new SpeechSynthesisUtterance(speechText)
  utterance.rate = 0.9
  utterance.pitch = 1
  utterance.volume = 1
  
  // Get available voices and select a good one
  const voices = speechSynthesis.getVoices()
  const preferredVoice = voices.find(voice => 
    voice.lang.includes('en') && (voice.name.includes('Female') || voice.name.includes('Woman'))
  ) || voices.find(voice => voice.lang.includes('en')) || voices[0]
  
  if (preferredVoice) {
    utterance.voice = preferredVoice
  }

  speechSynthesis.speak(utterance)
  return utterance
}

// ── Stop audio playback ────────────────────────────────────────────────
function stopAudio() {
  if ('speechSynthesis' in window) {
    speechSynthesis.cancel()
  }
}

